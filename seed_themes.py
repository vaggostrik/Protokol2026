def seed():
    init_db()
    session = get_session()
    added = 0
    skipped = 0
    try:
        existing_codes = {t.code for t in session.query(DocumentTheme).all()}
        existing_names = {t.name for t in session.query(DocumentTheme).all()}

        for code, name, desc in THEMES:
            if code in existing_codes or name in existing_names:
                print(f"  [παράλειψη] {code} - {name}  (ήδη υπάρχει)")
                skipped += 1
                continue
            session.add(DocumentTheme(code=code, name=name, description=desc, active=True))
            print(f"  [+] {code} - {name}")
            added += 1

        session.commit()
        print(f"\n  ✔  Προστέθηκαν {added} θέματα. Παραλείφθηκαν {skipped} (υπήρχαν ήδη).")
    except Exception as e:
        session.rollback()
        print(f"\n  [ΣΦΑΛΜΑ] {e}")
        raise
    finally:
        session.close()


